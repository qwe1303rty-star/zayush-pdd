export type VoiceKey = keyof typeof VOICE;
export type VoiceOverrides = Partial<Record<VoiceKey, string[]>>;

export function voiceVariants(key: VoiceKey, overrides?: VoiceOverrides): readonly string[] {
  const o = overrides?.[key];
  return o && o.length ? o : VOICE[key];
}

/** Выбирает фразу. seed позволяет не повторять одну и ту же фразу подряд. */
export function say(
  key: VoiceKey,
  opts: { seed?: number; vars?: Record<string, string | number>; overrides?: VoiceOverrides } = {},
): string {
  const variants = voiceVariants(key, opts.overrides);
  const idx = opts.seed === undefined ? Math.floor(Math.random() * variants.length) : Math.abs(opts.seed) % variants.length;
  let text = variants[idx] ?? '';
  for (const [k, v] of Object.entries(opts.vars ?? {})) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}
