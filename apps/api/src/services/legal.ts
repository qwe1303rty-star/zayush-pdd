const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);

/** Обезличенный идентификатор субъекта для журнала согласий: по нему нельзя восстановить Telegram ID без секрета */
export function subjectHash(env: Env, telegramId: bigint | number | string): string {
  return createHmac('sha256', env.PD_HASH_SECRET).update(`tg:${telegramId}`).digest('hex');
}

export function phoneHash(env: Env, phone: string): string {
  return createHmac('sha256', env.PD_HASH_SECRET).update(`phone:${phone}`).digest('hex');
}

